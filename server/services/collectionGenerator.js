
const SwaggerParser = require('@apidevtools/swagger-parser')

async function generateCollection(docsUrl) {
  const api = await SwaggerParser.validate(docsUrl)

  const baseUrl =
    api.servers?.[0]?.url ||
    'https://petstore3.swagger.io/api/v3'

  const items = []

  const supportedMethods = [
    'get',
    'post',
    'put',
    'patch',
    'delete',
    'options',
    'head',
    'trace',
  ]

  for (const [path, pathItem] of Object.entries(api.paths || {})) {
    for (const method of supportedMethods) {
      const operation = pathItem?.[method]
      if (!operation) continue

      const parameters = [
        ...(pathItem.parameters || []),
        ...(operation.parameters || []),
      ]

      // Create path variables.
      const pathVariables = parameters
        .filter(parameter => parameter.in === 'path')
        .map(parameter => ({
          key: parameter.name,
          value: `{{${parameter.name}}}`,
          description: parameter.description || '',
        }))

      // Create query parameters.
      const queryParameters = parameters
        .filter(parameter => parameter.in === 'query')
        .map(parameter => ({
          key: parameter.name,
          value:
            parameter.example !== undefined
              ? String(parameter.example)
              : parameter.schema?.default !== undefined
                ? String(parameter.schema.default)
                : parameter.schema?.enum?.[0] !== undefined
                  ? String(parameter.schema.enum[0])
                  : '',
          description: parameter.description || '',
          disabled: !parameter.required,
        }))

      const cleanBaseUrl = baseUrl.replace(/\/+$/, '')
      const cleanPath = path.replace(/^\/+/, '')

      // Replace path parameters with Postman variables.
      const resolvedPath = cleanPath.replace(
        /\{([^}]+)\}/g,
        (_, name) => `{{${name}}}`
      )

      // Include enabled query parameters in the URL.
      const queryString = queryParameters
        .filter(parameter => !parameter.disabled && parameter.value !== '')
        .map(
          parameter =>
            `${encodeURIComponent(parameter.key)}=${encodeURIComponent(parameter.value)}`
        )
        .join('&')

      const requestUrl =
        `${cleanBaseUrl}/${resolvedPath}` +
        (queryString ? `?${queryString}` : '')

      console.log('Generated request URL:', requestUrl)

      const request = {
        method: method.toUpperCase(),
        header: [],
        url: requestUrl,
        description: operation.description || operation.summary || '',
      }

      // Generate a sample JSON body when documented.
      const requestBody = operation.requestBody

      if (requestBody) {
        const content = requestBody.content || {}

        const jsonContent =
          content['application/json'] ||
          Object.entries(content).find(([contentType]) =>
            /^application\/.+\+json$/i.test(contentType)
          )?.[1]

        if (jsonContent) {
          request.header.push({
            key: 'Content-Type',
            value: 'application/json',
          })

          request.body = {
            mode: 'raw',
            raw: JSON.stringify(
              createExample(jsonContent.schema),
              null,
              2
            ),
            options: {
              raw: {
                language: 'json',
              },
            },
          }
        }
      }

      // Add documented response examples.
      const responseExamples = Object.entries(
        operation.responses || {}
      ).map(([status, response]) => ({
        name: `Expected response: ${status}`,
        originalRequest: request,
        status: response.description || 'Documented response',
        code: /^\d{3}$/.test(status) ? Number(status) : 200,
        header: [],
        body: '',
      }))

      items.push({
        name: operation.summary || `${method.toUpperCase()} ${path}`,
        request,
        response: responseExamples,
      })
    }
  }

  return {
    info: {
      name: api.info?.title || 'SpecPilot API Collection',
      description: `Generated by SpecPilot from OpenAPI ${
        api.info?.version || ''
      }`,
      schema:
        'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
    },
    item: items,
    variable: [
      {
        key: 'baseUrl',
        value: baseUrl,
        type: 'string',
      },
    ],
  }
}

function createExample(schema, depth = 0) {
  if (!schema || depth > 5) return {}

  if (schema.example !== undefined) return schema.example
  if (schema.default !== undefined) return schema.default

  if (schema.type === 'object' || schema.properties) {
    const result = {}

    for (const [key, property] of Object.entries(
      schema.properties || {}
    )) {
      result[key] = createExample(property, depth + 1)
    }

    return result
  }

  if (schema.type === 'array') {
    return [createExample(schema.items, depth + 1)]
  }

  if (schema.enum?.length) return schema.enum[0]

  switch (schema.type) {
    case 'string':
      return 'example'
    case 'integer':
    case 'number':
      return 0
    case 'boolean':
      return false
    default:
      return {}
  }
}

module.exports = { generateCollection }
